bool connectToWiFi(const char* ssid, const char* password, uint8_t maxAttempts) {
    WiFi.mode(WIFI_STA);
    WiFi.setAutoReconnect(true);
    WiFi.begin(ssid, password);

    for (uint8_t attempt = 0; attempt < maxAttempts; ++attempt) {
        if (WiFi.status() == WL_CONNECTED) {
            return true;
        }
        delay(500);
    }

    return false;
}

bool fetchWeatherData(WeatherData& data, String& statusMessage) {
    if (WiFi.status() != WL_CONNECTED) {
        statusMessage = "WiFi not connected";
        return false;
    }

    WiFiClientSecure client;
    client.setInsecure();
    client.setHandshakeTimeout(30);

    HTTPClient http;
    String uri = String("/data/2.5/weather?lat=") + OPENWEATHER_LAT + "&lon=" + OPENWEATHER_LON + "&appid=" + OPENWEATHER_API_KEY + "&units=imperial";

    if (!http.begin(client, kServerHost, kServerPort, uri)) {
        statusMessage = "HTTP init failed";
        return false;
    }

    int httpResponseCode = http.GET();
    Serial.print("HTTP Response Code: ");
    Serial.println(httpResponseCode);

    if (httpResponseCode != HTTP_CODE_OK) {
        statusMessage = "HTTP Error: " + String(httpResponseCode);
        http.end();
        return false;
    }

    String payload = http.getString();
    http.end();

    JsonDocument doc;
    DeserializationError error = deserializeJson(doc, payload);
    if (error) {
        statusMessage = "JSON Unpack Fail";
        return false;
    }

    data.city = doc["name"].as<String>();
    if (data.city.length() == 0) {
        data.city = "Calhoun";
    }

    data.dt = doc["dt"].as<long long>();
    data.timezoneSeconds = doc["timezone"].as<long long>();

    data.temperatureF = doc["main"]["temp"].as<float>();
    data.feelsLikeF = doc["main"]["feels_like"].as<float>();
    data.minTempF = doc["main"]["temp_min"].as<float>();
    data.maxTempF = doc["main"]["temp_max"].as<float>();
    data.humidity = doc["main"]["humidity"].as<int>();
    data.windSpeed = doc["wind"]["speed"].as<float>();

    JsonArray weatherArray = doc["weather"].as<JsonArray>();
    if (weatherArray.size() > 0) {
        data.description = weatherArray[0]["description"].as<String>();
        data.iconCode = weatherArray[0]["icon"].as<String>();
    } else {
        data.description = "CLOUDY";
        data.iconCode = "01d";
    }

    data.description.toUpperCase();
    statusMessage = "";
    return true;
}

