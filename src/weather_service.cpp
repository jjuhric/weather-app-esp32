uint16_t getTemperatureColorCode(float temperatureF)
{
    if (temperatureF < 60.0f)
    {
        return TFT_BLUE; // Super Cold
    }
    else if (temperatureF < 70.0f)
    {
        return TFT_CYAN; // Cool
    }
    else if (temperatureF < 80.0f)
    {
        return TFT_WHITE; // Mild
    }
    else if (temperatureF < 90.0f)
    {
        return TFT_YELLOW; // Warm
    }
    else
    {
        return TFT_RED; // Hot
    }
}
bool connectToWiFi(const char *ssid, const char *password, uint8_t maxAttempts)
{
    WiFi.mode(WIFI_STA);
    WiFi.setAutoReconnect(true);
    WiFi.begin(ssid, password);

    for (uint8_t attempt = 0; attempt < maxAttempts; ++attempt)
    {
        if (WiFi.status() == WL_CONNECTED)
        {
            return true;
        }
        delay(500);
    }

    return false;
}

bool isInternetReachable(uint16_t timeoutMs)
{
    if (WiFi.status() != WL_CONNECTED)
    {
        return false;
    }

    WiFiClient probeClient;
    bool connected = probeClient.connect(kServerHost, kServerPort, timeoutMs);
    if (connected)
    {
        probeClient.stop();
    }

    return connected;
}

