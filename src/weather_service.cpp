// Scaling/drawing helper: upscale 64x64 bitmaps to desired size
// maskX/Y/W/H: optional region in source coords to suppress (set maskX<0 to disable)
void drawScaledBitmap(int x, int y, const unsigned char* bitmap, int w, int h, int nw, int nh, uint16_t color,
                      int maskX = -1, int maskY = -1, int maskW = 0, int maskH = 0) {
    for (int j = 0; j < nh; ++j) {
        int srcY = (j * h) / nh;
        for (int i = 0; i < nw; ++i) {
            int srcX = (i * w) / nw;

            // If mask enabled and this source pixel falls inside, skip drawing it
            if (maskX >= 0) {
                if (srcX >= maskX && srcX < (maskX + maskW) && srcY >= maskY && srcY < (maskY + maskH)) {
                    continue;
                }
            }

            int byteIndex = srcY * ((w + 7) / 8) + (srcX / 8);
            int bitIndex = 7 - (srcX % 8);
            if (pgm_read_byte(&bitmap[byteIndex]) & (1 << bitIndex)) {
                tft.drawPixel(x + i, y + j, color);
            }
        }
    }
}

uint16_t getIconColor(const String& iconCode) {
    uint16_t color;
    if (iconCode.startsWith("01")) {
        color = TFT_YELLOW; // Sunny
    } else if (iconCode.startsWith("02") || iconCode.startsWith("03") || iconCode.startsWith("04")) {
        color = TFT_LIGHTGREY; // Cloudy
    } else if (iconCode.startsWith("09") || iconCode.startsWith("10") || iconCode.startsWith("11")) {
        color = TFT_DARKCYAN; // Rainy
    } else if (iconCode.startsWith("50")) {
        color = TFT_CYAN; // Windy
    } else {
        color = TFT_WHITE; // Default
    }
    return color;
}

// Select and draw the appropriate bitmap, scaled to fill the region
